import sys
import math


def main():
    # 我自己读取输入、完成计算并输出结果
    n=int(sys.stdin.readline().strip())
    nums=list(map(float,sys.stdin.readline().split()))
    mean=sum(nums)/n
    a=0
    for num in nums:
        a=(num-mean)*(num-mean)+a
    variance=a/n
    std=math.sqrt(variance)
    print(f"{mean:.6f}")
    print(f"{variance:.6f}")
    print(f"{std:.6f}")


if __name__ == "__main__":
    main()

